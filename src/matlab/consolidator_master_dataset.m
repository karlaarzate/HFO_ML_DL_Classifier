%% =========================================================================
%  PART 2: HFO DATASET COMPILER
%
%  Objective:
%  Systematically aggregate individual patient feature files (Parquet format) 
%  into a consolidated Master Dataset for Machine Learning training.
%
%  Key Functionalities:
%  - Metadata Extraction: Parses subject identifiers directly from filenames.
%  - Data Integrity: Implements robust error handling for corrupted files.
%  - Forensic Diagnostics: Validates class balance and patient diversity 
%    required for Leave-One-Patient-Out (LOPO) cross-validation.
% =========================================================================

clear; clc; close all;

% -------------------------------------------------------------------------
% 1. SYSTEM CONFIGURATION
% -------------------------------------------------------------------------

% Get the script's current location (src/matlab/)
current_path = fileparts(mfilename('fullpath'));

% Move up two levels to the Project Root (HFO-Hybrid-Detection/)
project_root = fullfile(current_path, '..', '..');

% Define Inbound and Outbound paths
% We read from 'processed/FEATURES' and save to 'master'
FEATURES_DIR  = fullfile(project_root, 'data', 'processed', 'FEATURES');
MASTER_DIR    = fullfile(project_root, 'data', 'master');
OUTPUT_FILE   = fullfile(MASTER_DIR, 'HFO_MASTER_DATASET_200ms.parquet');

% Ensure the 'master' directory exists
if ~exist(MASTER_DIR, 'dir')
    mkdir(MASTER_DIR);
    fprintf('[INFO] Created master data directory: %s\n', MASTER_DIR);
end

% -------------------------------------------------------------------------
% 2. DIRECTORY AUDIT
% -------------------------------------------------------------------------
fprintf('[INFO] Initiating Dataset Merger Process...\n');

% Verify that features were actually generated by the previous script
if ~exist(FEATURES_DIR, 'dir')
    error('[ERROR] Target directory not found: %s. Run preprocessing first.', FEATURES_DIR); 
end

% Scan for parquet files generated per patient
fileList = dir(fullfile(FEATURES_DIR, '*_features.parquet'));
numFiles = length(fileList);

if numFiles == 0
    error('[ERROR] No valid feature files detected in: %s', FEATURES_DIR); 
end

fprintf('[INFO] Detected %d feature files in "data/processed/FEATURES".\n', numFiles);
fprintf('[INFO] The consolidated dataset will be saved in "data/master/".\n');

% -------------------------
% 3. DATA INGESTION & AGGREGATION LOOP
% -------------------------
tableCellArray = {}; 
tic;
validCount = 0;

for i = 1:numFiles
    filePath = fullfile(fileList(i).folder, fileList(i).name);
    try
        T = parquetread(filePath);
        
        % --- SUBJECT IDENTIFICATION LOGIC ---
        % Logic: Extracts 'pat_XX' pattern from naming convention
        tokens = split(fileList(i).name, '_');
        if length(tokens) >= 3
            patientID = strjoin(tokens(2:3), '_'); 
        else
            patientID = "unknown_subject";
        end
        
        % Normalize Subject Column
        T.Patient = repmat(string(patientID), height(T), 1);
        
        % Store validated table
        validCount = validCount + 1;
        tableCellArray{validCount} = T;
        
        if mod(i, 50) == 0
            fprintf('[PROGRESS] Successfully ingested %d / %d files...\n', i, numFiles);
        end
    catch ME
        fprintf('[WARNING] Skipping file: %s. Exception: %s\n', fileList(i).name, ME.message);
    end
end

if isempty(tableCellArray)
    error('[CRITICAL] No data was successfully loaded. Ingestion process aborted.');
end

fprintf('[INFO] Performing vertical concatenation on %d tables...\n', length(tableCellArray));
MasterTable = vertcat(tableCellArray{:});
clear tableCellArray; 
elapsedTime = toc;
fprintf('[SUCCESS] Master Dataset compiled in %.2f seconds.\n', elapsedTime);

% =========================================================================
% 4. DATASET FORENSIC DIAGNOSTICS
% =========================================================================
separator = repmat('=', 1, 50);
fprintf('\n%s\n', separator);
fprintf('       BIOMEDICAL DATASET INTEGRITY REPORT\n');
fprintf('%s\n', separator);

isDatasetValid = true;
currentVars = MasterTable.Properties.VariableNames;

% --- MODULE A: SCHEMA VERIFICATION ---
fprintf('\n[1] FEATURE SPACE ARCHITECTURE:\n');
disp(currentVars');

% --- MODULE B: SUBJECT DIVERSITY AUDIT ---
fprintf('\n[2] COHORT REPRESENTATION CHECK:\n');
if ismember('Patient', currentVars)
    uniquePats = unique(MasterTable.Patient);
    numPats = length(uniquePats);
    fprintf('   - Unique Subjects detected: %d\n', numPats);
    fprintf('   - Subject IDs: %s\n', strjoin(uniquePats, ', '));
    
    if numPats < 2
   % debbugin (using only one patient):
   %if numPats < 1
        fprintf('   [CRITICAL] Multi-subject diversity required for LOPO validation. Found: %d\n', numPats);
        isDatasetValid = false;
    else
        fprintf('   [VERIFIED] Cohort diversity meets cross-validation standards.\n');
    end
else
    fprintf('   [CRITICAL] Mandatory metadata column "Patient" is absent.\n');
    isDatasetValid = false;
end

% --- MODULE C: CLASS PREVALENCE ANALYSIS ---
fprintf('\n[3] TARGET CLASS DISTRIBUTION (yAnyHFO):\n');
if ismember('yAnyHFO', currentVars)
    totalRows = height(MasterTable);
    
    % Quantitative Class Tally
    numHFO = sum(double(MasterTable.yAnyHFO) == 1);
    numNoise = totalRows - numHFO;
    
    % Prevalence Percentages
    perHFO = (numHFO / totalRows) * 100;
    perNoise = (numNoise / totalRows) * 100;
    
    fprintf('   - Total Observations: %d\n', totalRows);
    fprintf('   - HFO Events (Positive): %d (%.2f%%)\n', numHFO, perHFO);
    fprintf('   - Background Noise (Negative): %d (%.2f%%)\n', numNoise, perNoise);
    
    if numHFO == 0 || numNoise == 0
        fprintf('   [CRITICAL] Categorical failure: Null prevalence in one or more classes.\n');
        isDatasetValid = false;
    end
else
    fprintf('   [CRITICAL] Target variable "yAnyHFO" not found in schema.\n');
    isDatasetValid = false;
end

% --- MODULE D: QUALITY ASSURANCE (NULL VALUE AUDIT) ---
if ismember('GaborCorrelation', currentVars)
    nanCount = sum(isnan(MasterTable.GaborCorrelation));
    if nanCount > 0
        fprintf('\n[ADVISORY] Quality Assurance: %d NaN values identified in GaborCorrelation metric.\n', nanCount);
    end
end

% -------------------------
% 5. FINAL EXPORT PROTOCOL
% -------------------------
fprintf('\n%s\n', separator);
if isDatasetValid
    fprintf('[STATUS] Validation Status: PASSED.\n');
    try
        fprintf('[EXPORT] Serialization initiated: %s\n', OUTPUT_FILE);
        parquetwrite(OUTPUT_FILE, MasterTable);
        fprintf('[SUCCESS] Master Dataset finalized and ready for Model Training.\n');
    catch ME
        fprintf('[ERROR] Serialization failed: %s\n', ME.message);
    end
else
    fprintf('[STATUS] Validation Status: FAILED. Manual intervention required.\n');
end
